import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { mountCharacterSurfaces } from '../adapters/harness/character.mjs';
import { createActivityTracker } from '../adapters/harness/activity.mjs';

// Use the same function embedding boundary as the installed plugin. The review
// page needs no adapter static-file route and no Electron/React dependency.
export function reviewRuntimeSource() {
  const body = [mountCharacterSurfaces, createActivityTracker].map(fn => `export ${fn.toString()}`).join('\n\n');
  const sha = createHash('sha256').update(body).digest('hex');
  return `// Generated by scripts/build-tool-presentation-review.mjs. Do not edit.\n// Exact production controller + tracker function bodies; SHA-256 ${sha}.\n${body}\n`;
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await writeFile(new URL('../web/tool-presentation-runtime.mjs', import.meta.url), reviewRuntimeSource());
}
