import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { ACTION_STATES } from '../src/skin.mjs';

// Convert inspected face centers into CSS background positions. No PNG pixels
// are changed. Run again whenever an independently generated action is replaced.
const root = new URL('../', import.meta.url);
const allowPartial = process.argv.includes('--allow-partial');
const introKeys = ['away','turning','front-neutral','front-smile'];
const output = {};
for (const [id, manifest] of [['serene','serene'],['maid','maid'],['maid_chibi','chibi']]) {
  const data = JSON.parse(await readFile(new URL(`docs/${manifest}-action-generation-v1.json`,root),'utf8'));
  const entry = output[id] = { states:{}, intro:{} };
  const zoom = id === 'maid_chibi' ? 2.8 : 4.8;
  for (const row of data.assets || data.records) {
    const key = row.state || row.key;
    const [x,y] = row.faceCenter || [];
    if (![x,y].every(value=>Number.isFinite(value)&&value>=0&&value<=1)) throw Error(`${id}/${key}: missing inspected faceCenter`);
    const percent = value=>Math.max(0,Math.min(100,value)).toFixed(2);
    const frame = {focus:`${percent((zoom*x-.5)/(zoom-1)*100)}% ${percent((zoom*1.5*y-.5)/(zoom*1.5-1)*100)}%`,scale:row.backgroundScale||`${zoom*100}% auto`};
    if(key.startsWith('intro-')) entry.intro[key.slice(6)] = frame;
    else entry.states[key] = frame;
  }
  const extra = JSON.parse(await readFile(new URL(`docs/${manifest}-tool-actions-v2.json`,root),'utf8'));
  for (const row of extra.assets || extra.records) {
    const key=row.state || row.action;
    const center=row.faceCenter || (row.faceApproxPixels?[row.faceApproxPixels.cx/1024,row.faceApproxPixels.cy/1536]:[row.faceEstimate?.center.x/1024,row.faceEstimate?.center.y/1536]);
    const [x,y]=center;if(![x,y].every(Number.isFinite))throw Error(`${id}/${key}: missing new face center`);
    const percent=value=>Math.max(0,Math.min(100,value)).toFixed(2);
    entry.states[key]={focus:`${percent((zoom*x-.5)/(zoom-1)*100)}% ${percent((zoom*1.5*y-.5)/(zoom*1.5-1)*100)}%`,scale:`${zoom*100}% auto`};
  }
  // Command execution retains the original computer scene; generic work has
  // a new toolbox pose. Capture its focus before applying the v3 replacements.
  entry.states.executing=entry.states.working;
  const distinct = JSON.parse(await readFile(new URL(`docs/${manifest}-distinct-actions-v3.json`,root),'utf8'));
  for (const row of distinct.assets || distinct.records) {
    const key=row.state;
    const [x,y]=row.faceCenter || [];
    if(![x,y].every(value=>Number.isFinite(value)&&value>=0&&value<=1)) throw Error(`${id}/${key}: missing inspected v3 faceCenter`);
    const percent=value=>Math.max(0,Math.min(100,value)).toFixed(2);
    entry.states[key]={focus:`${percent((zoom*x-.5)/(zoom-1)*100)}% ${percent((zoom*1.5*y-.5)/(zoom*1.5-1)*100)}%`,scale:row.backgroundScale||`${zoom*100}% auto`};
  }
  // These four accepted concept keyframes were individually framed in the
  // browser before being promoted byte-for-byte to the production catalog.
  if(id==='maid') for (const [key,focus] of Object.entries({away:'43% 5%',turning:'47% 6.5%','front-neutral':'50% 8%','front-smile':'50% 8%'})) entry.intro[key]={focus,scale:'480% auto'};
  if(!allowPartial) for(const [group,keys] of [['states',ACTION_STATES],['intro',introKeys]]) {
    if(Object.keys(entry[group]).length!==keys.length || keys.some(key=>!entry[group][key])) throw Error(`${id}: incomplete ${group}`);
  }
}
const destination = new URL('src/action-focus.mjs',root);
await writeFile(destination,`// Generated by scripts/update-action-focus.mjs from inspected artwork.\nexport const ACTION_FOCUS = ${JSON.stringify(output,null,2)};\n`);
console.log(`Updated ${fileURLToPath(destination)}${allowPartial?' (partial development catalog)':''}`);
